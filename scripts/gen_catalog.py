#!/usr/bin/env python3
"""Generate docs/TOOL_CATALOG.md from the live MCP tool registration.

Usage:
    python scripts/gen_catalog.py            # writes docs/TOOL_CATALOG.md
    python scripts/gen_catalog.py --check    # exit 1 if the file is stale (CI)

The catalog is generated, never hand-edited: it lists every registered tool
with its first docstring line, grouped by the section comments in app.py.
"""

from __future__ import annotations

import argparse
import asyncio
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = ROOT / "docs" / "TOOL_CATALOG.md"
HEADER = """<!-- generated by scripts/gen_catalog.py — do not edit by hand -->

# Tool catalog

{count} tools as registered in `osint_mcp/app.py`. Regenerate with:

```bash
python scripts/gen_catalog.py
```
"""


def _sections() -> list[tuple[str, list[str]]]:
    """Parse app.py TOOLS list into (section_title, tool_names) chunks."""
    source = (ROOT / "osint_mcp" / "app.py").read_text(encoding="utf-8")
    match = re.search(r"^TOOLS\s*=\s*\[(.*?)^\]", source, re.S | re.M)
    if not match:  # pragma: no cover - app.py always defines TOOLS
        return [("All tools", [])]
    body = match.group(1)
    sections: list[tuple[str, list[str]]] = []
    current_title = "Core"
    for line in body.splitlines():
        stripped = line.strip()
        section = re.match(r"^#\s+(.+)$", stripped)
        if section:
            current_title = section.group(1).strip()
            continue
        name = re.match(r"^([a-zA-Z_][a-zA-Z0-9_.]*)\.([a-zA-Z_][a-zA-Z0-9_]*)\s*,?\s*$", stripped)
        if name:
            if not sections or sections[-1][0] != current_title:
                sections.append((current_title, []))
            sections[-1][1].append(name.group(2))
    return sections


def build_markdown() -> str:
    sys.path.insert(0, str(ROOT))
    from osint_mcp.app import mcp

    tools = {tool.name: tool for tool in asyncio.run(mcp.list_tools())}
    lines = [HEADER.format(count=len(tools))]
    for title, names in _sections():
        lines.append(f"\n## {title}\n")
        lines.append("| Tool | Description |")
        lines.append("|---|---|")
        missing = []
        for name in names:
            tool = tools.get(name)
            if tool is None:
                missing.append(name)
                continue
            description = (tool.description or "").strip().splitlines()
            first = description[0].rstrip(".") if description else ""
            lines.append(f"| `{name}` | {first} |")
        for name in missing:
            print(f"WARNING: {name} listed in app.py but not registered", file=sys.stderr)
    registered = {tool.name for tool in tools.values()}
    listed = {name for _, names in _sections() for name in names}
    for extra in sorted(registered - listed):
        print(f"WARNING: {extra} registered but not listed in a section", file=sys.stderr)
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/TOOL_CATALOG.md is stale")
    args = parser.parse_args()
    markdown = build_markdown()
    if args.check:
        if not OUT_PATH.is_file():
            print(f"missing {OUT_PATH}", file=sys.stderr)
            return 1
        if OUT_PATH.read_text(encoding="utf-8") != markdown:
            print(f"{OUT_PATH} is stale — run: python scripts/gen_catalog.py", file=sys.stderr)
            return 1
        print(f"catalog up to date ({OUT_PATH})")
        return 0
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(markdown, encoding="utf-8")
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
